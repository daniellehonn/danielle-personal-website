#!/usr/bin/env python3
"""
Rewrite the image references in shared/content.js from what is actually on
disk. Run after adding, renaming or removing anything under assets/shots.

    python3 tools/sync-assets.py

Three things are regenerated:

  ANNOTATIONS        one entry per about-me/<folder>, in FOLDER order
  EXPERIENCE .shots  for any entry whose code appears in EXPERIENCE_DIRS
  PROJECTS .img      for any slug in PROJECT_IMG whose file exists

Captions are not touched here. They live in CAPTIONS below, keyed by file
path, and only exist where a photograph cannot say what it is itself.
"""
import io, os, glob, json, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

EXTS = ('*.jpg', '*.jpeg', '*.png', '*.webp')

# about-me/<folder>  ->  the phrase in PERSON.about it reveals under
FOLDER = [
  ("me",       "Danielle Hon"),
  ("la",       "Los Angeles"),
  ("details",  "a well-cropped photo"),
  ("playlist", "a curated playlist"),
  ("pins",     "a Pinterest board at 1am"),
  ("coffee",   "tasting americanos at new cafes"),
  ("walk",     "on a walk"),
]
# products sit under their own phrase, and carry their names
PRODUCT_PHRASE = "a tasteful landing page"
PRODUCT_AFTER  = 4          # where that group sits in the list
PRODUCTS = [
  ('assets/shots/projects/contextforce/forty-pirates/forty-pirates-landing.jpg', 'Forty Pirates'),
  ('assets/shots/projects/contextforce/lexi/lexi-logo.jpg',                      'LEXI'),
  ('assets/shots/projects/plan-my-courses/plan-my-courses-ui.jpg',               'Plan My Courses'),
  ('assets/shots/projects/contextforce/ai-vision-benchmark/ai-vision-benchmark-01.png', 'AI Vision Benchmark'),
  ('assets/shots/projects/contextforce/pdf-extractor-demo/pdf-extract-demo-01.png',     'PDF Extractor Demo'),
]
# hero image per project slug
PROJECT_IMG = {
  'forty-pirates':       'assets/shots/projects/contextforce/forty-pirates/forty-pirates-landing.jpg',
  'lexi':                'assets/shots/projects/contextforce/lexi/lexi-logo.jpg',
  'course-planner':      'assets/shots/projects/plan-my-courses/plan-my-courses-ui.jpg',
  'ai-vision-benchmark': 'assets/shots/projects/contextforce/ai-vision-benchmark/ai-vision-benchmark-01.png',
  'pdf-extractor-demo':  'assets/shots/projects/contextforce/pdf-extractor-demo/pdf-extract-demo-01.png',
}
# EXPERIENCE code -> folder of photographs for that entry
EXPERIENCE_DIRS = { 'University of California, Los Angeles': 'assets/shots/ucla' }

# only where the photograph cannot say it itself
CAPTIONS = {}

def shots_in(d):
    out = []
    for e in EXTS:
        out += glob.glob(os.path.join(d, e))
    return sorted(out)

def block(groups):
    lines = []
    for phrase, shots in groups:
        lines.append('  { "phrase":%s, "shots":[' % json.dumps(phrase))
        lines.append(',\n'.join('    { "src":%s, "cap":%s }'
                                % (json.dumps(s), json.dumps(CAPTIONS.get(s, "")))
                                for s in shots))
        lines.append('  ]},')
    lines[-1] = lines[-1].rstrip(',')
    return ('// ─────────────────────────────────────────────────────────────────────\n'
      '// ANNOTATIONS. Phrases in the About copy that reveal a photograph on\n'
      '// hover. `phrase` must appear verbatim in PERSON.about. Hovering shows\n'
      '// one print; moving within the phrase flips through its set.\n'
      '//\n'
      '// GENERATED by tools/sync-assets.py from assets/shots/about-me/<folder>.\n'
      '// Drop a file into a folder and re-run it; do not edit this by hand.\n'
      '// ─────────────────────────────────────────────────────────────────────\n'
      'var ANNOTATIONS = [\n' + '\n'.join(lines) + '\n];\n\n')

def main():
    groups, missing = [], []
    for folder, phrase in FOLDER:
        files = shots_in(os.path.join('assets/shots/about-me', folder))
        if files: groups.append((phrase, files))
        else: missing.append('about-me/' + folder)
    prods = [(p, c) for p, c in PRODUCTS if os.path.exists(p)]
    for p, c in PRODUCTS:
        if not os.path.exists(p): missing.append(p)
    if prods:
        groups.insert(PRODUCT_AFTER, (PRODUCT_PHRASE, [p for p, _ in prods]))
        for p, c in prods: CAPTIONS[p] = c

    s = io.open('shared/content.js', encoding='utf-8').read()
    a = s.index('// ─────────────────────────────────────────────────────────────────────\n// ANNOTATIONS.')
    b = s.index('\n// ── generated block ends')
    s = s[:a] + block(groups) + s[b:]

    # PROJECTS .img
    for slug, path in PROJECT_IMG.items():
        if not os.path.exists(path): missing.append(path); continue
        i = s.index('"slug": "%s"' % slug)
        j = s.index('"img":', i); e = s.index('\n', j)
        s = s[:j] + '"img": %s,' % json.dumps(path) + s[e:]

    # EXPERIENCE .shots
    s = re.sub(r'\n    "shots": \[.*?\n    \],', '', s, flags=re.S)
    for code, d in EXPERIENCE_DIRS.items():
        files = shots_in(d)
        if not files: missing.append(d); continue
        body = ',\n'.join('      { "src":%s, "cap":%s }'
                          % (json.dumps(f), json.dumps(CAPTIONS.get(f, ""))) for f in files)
        i = s.index('"org": "%s"' % code); e = s.index('\n', i)
        s = s[:e+1] + '    "shots": [\n' + body + '\n    ],\n' + s[e+1:]

    io.open('shared/content.js', 'w', encoding='utf-8').write(s)

    total = sum(len(g[1]) for g in groups)
    for phrase, files in groups:
        print('  %-34s %d' % (phrase, len(files)))
    print('%d annotation slots' % total)
    if missing:
        print('MISSING (referenced but not on disk):')
        for m in missing: print('  ', m)
        return 1
    return 0

sys.exit(main())
