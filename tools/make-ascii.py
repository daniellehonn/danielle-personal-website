#!/usr/bin/env python3
"""Turn an image into a braille-ASCII mark for the hero.

    python3 tools/make-ascii.py assets/cat02.png cat-brush --mode outline

Writes assets/ascii/<name>.js. Switch the hero to it by pointing the
<script src> in index.html at that file — see assets/ascii/README.md.

Modes:
  outline  traces edges. Use this. Braille dots are circles with gaps, so a
           filled shape only reaches ~50% ink coverage and renders as grey
           mush; braille draws lines well and masses badly.
  solid    fills the shape. Included for comparison; rarely the right call.

macOS only: uses `sips` to resample, since PIL isn't installed here.
"""
import io, os, re, struct, subprocess, sys, argparse, tempfile

BLANK = '⠀'
# (dx, dy, bit) for the 8 dots in one braille cell: 2 wide x 4 tall
DOTS = [(0,0,0x01),(0,1,0x02),(0,2,0x04),(1,0,0x08),
        (1,1,0x10),(1,2,0x20),(0,3,0x40),(1,3,0x80)]


def read_bmp(path):
    d = open(path, 'rb').read()
    off = struct.unpack_from('<I', d, 10)[0]
    w, h = struct.unpack_from('<ii', d, 18)
    bpp = struct.unpack_from('<H', d, 28)[0]
    flip = h > 0
    h = abs(h)
    row = ((w * bpp // 8) + 3) // 4 * 4
    px = [[0] * w for _ in range(h)]
    for y in range(h):
        sy = (h - 1 - y) if flip else y
        base = off + sy * row
        for x in range(w):
            p = base + x * (bpp // 8)
            b, g, r = d[p], d[p+1], d[p+2]
            px[y][x] = (r*299 + g*587 + b*114) // 1000
    return w, h, px


def trim(rows):
    while rows and set(rows[0]) <= {BLANK}: rows.pop(0)
    while rows and set(rows[-1]) <= {BLANK}: rows.pop()
    while rows and all(r[0] == BLANK for r in rows): rows = [r[1:] for r in rows]
    while rows and all(r[-1] == BLANK for r in rows): rows = [r[:-1] for r in rows]
    return rows


def render(px, w, h, mode, thresh):
    def ink(x, y):
        return px[y][x] < thresh

    def on(x, y):
        if x >= w or y >= h: return False
        if mode == 'solid': return ink(x, y)
        if not ink(x, y): return False
        for dx, dy in ((1,0),(-1,0),(0,1),(0,-1),(2,0),(-2,0),(0,2),(0,-2)):
            nx, ny = x + dx, y + dy
            if nx < 0 or ny < 0 or nx >= w or ny >= h or not ink(nx, ny):
                return True
        return False

    rows = []
    for cy in range(0, h // 4 * 4, 4):
        line = ''
        for cx in range(0, w // 2 * 2, 2):
            v = 0
            for dx, dy, bit in DOTS:
                if on(cx + dx, cy + dy): v |= bit
            line += chr(0x2800 + v)
        rows.append(line)
    return trim(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('image')
    ap.add_argument('name', help='output key, e.g. cat-brush')
    ap.add_argument('--mode', choices=['outline', 'solid'], default='outline')
    ap.add_argument('--res', type=int, default=96, help='dot grid; 96 suits a 300px box')
    ap.add_argument('--thresh', type=int, default=140, help='0-255 ink cutoff')
    a = ap.parse_args()

    if not re.fullmatch(r'[a-z0-9-]+', a.name):
        sys.exit('name must be lowercase letters, digits and dashes')

    # Flatten alpha onto white by routing through JPEG first. sips composites
    # transparency onto BLACK when it writes a BMP, which inverts a transparent
    # PNG into a solid ink field and traces a frame around the whole image.
    with tempfile.NamedTemporaryFile(suffix='.jpg', delete=False) as tf:
        jpg = tf.name
    with tempfile.NamedTemporaryFile(suffix='.bmp', delete=False) as tf:
        bmp = tf.name
    try:
        for cmd in (['sips', '-s', 'format', 'jpeg', '-s', 'formatOptions', 'best',
                     a.image, '--out', jpg],
                    ['sips', '-z', str(a.res), str(a.res), '-s', 'format', 'bmp',
                     jpg, '--out', bmp]):
            r = subprocess.run(cmd, capture_output=True)
            if r.returncode:
                sys.exit('sips failed: ' + r.stderr.decode()[:200])
        w, h, px = read_bmp(bmp)
        corners = [px[0][0], px[0][w-1], px[h-1][0], px[h-1][w-1]]
        if all(c < a.thresh for c in corners):
            print('  ! all four corners read as ink — check --thresh or the source image')
    finally:
        os.unlink(jpg); os.unlink(bmp)

    rows = render(px, w, h, a.mode, a.thresh)
    if not rows:
        sys.exit('nothing rendered — try a different --thresh')

    out = os.path.join('assets', 'ascii', a.name + '.js')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    art = '\\n'.join(rows).replace('\\n', '\\n')
    body = 'var ASCII_MARK = "' + '\\n'.join(rows) + '";\n'
    io.open(out, 'w', encoding='utf-8').write(
        '// %s — %s, %d-dot grid, generated by tools/make-ascii.py\n'
        '// Point the <script src> in index.html here to use it.\n' % (a.name, a.mode, a.res)
        + body)
    print('  %s  %d cols x %d rows  -> %s' % (a.name, max(len(r) for r in rows), len(rows), out))


if __name__ == '__main__':
    main()
